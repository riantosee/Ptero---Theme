// Embeds backgrounds/*.jpg into src/backgrounds.css as data URIs.
// The panel serves only dist/theme.css for a CSS-only theme, so images must travel inside it.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const uri = (name) =>
    `url('data:image/jpeg;base64,${readFileSync(resolve(root, 'backgrounds', name)).toString('base64')}')`;

const css = `/* Generated by scripts/embed-backgrounds.mjs — edit backgrounds/*.jpg, not this file. */
:root {
  --lb-art-wide: ${uri('wide.jpg')};
  --lb-art-portrait: ${uri('portrait.jpg')};
}
`;

writeFileSync(resolve(root, 'src', 'backgrounds.css'), css);
console.log('src/backgrounds.css written');
